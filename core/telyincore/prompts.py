# telyincore/prompts.py
"""整理态那一段**给模型看的话** —— 指令 ／ 那两份的现状怎么摆 ／ 交回来那个对象的形状。

 **这一份的名字是设计给的**：`docs/design/10-整理态.md` §交付物那张表逐字写着

```
consolidate.py   编排：排队 / 串行 / 空跑保护 / 快照裁剪 / 浮现注入
prompts.py       整理态的指令（上面那段）
```

⇒ 那两个名字是**一处**设计，不是"占位名" —— 而这条更正有来历：本模块原先叫
`consolidate.py`（**照抄了参考实现里的标识符**），那时的补记还把这张表说成"设计时的占位名"。
⚠️ 而"梦"这个字在参考工程里**是那个人的会话 id**（`DREAM = 'dream'`，label
「梦(交接后台整理)」），不是机制名 —— `05-主循环与交接.md` §〇 为这件事专门写过一条
【订正】，点名的正是**把一个指称当成一个概念**。⇒ 本仓这一件事的正名是**整理态**。

⚠️⚠️ **它为什么单独一个文件**（而不是住在 `consolidate.py` 里）： 这一份是
   **"它写成什么样"唯一那处变量** —— 2026-10-03 第一次真跑就量出来了：
   那一版**没把那份正文摆在它眼前**，于是它交回一句「没有新东西要收……交回原样」，
   而那一句**真的变成了那一份的正文**（`.history-自述/自述-20261002-205707.md` 里留着）。
   ⇒ 那些字与"怎么排它"住在一起、**与编排分开**，下一个要改那句话的人一眼找得到它。

⚠️ **本模块一次都不碰 IO、不读时钟、不认识会话、不 import 本包任何东西**：
   它是**纯文字**（把几段拼成一条消息）。那几个决定都落在 `consolidate.py` 上。
"""
