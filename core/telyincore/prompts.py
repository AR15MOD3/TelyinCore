#: 那一段的正身（一个模块级常量 —— 判据可引用，不必自己再抄一份）。
INSTRUCTION = _instruction()


def the_ask(blocks: Sequence[tuple[str, str]], *, instruct: str = INSTRUCTION) -> str:
    """**那一段指令 ＋ 那两份的现状** —— 交给模型的那一条 user 消息（纯函数）。

    ⚠️⚠️ **为什么非有它不可**（第一次真跑量出来的那个洞，逐字写在 `_instruction` 那段）：
       没有工具的整理态**只有**这一条消息里的东西 —— 而"回头看你写自己的那一份"
       这件事，**先得把那一份放在它眼前**。 不给 ⇒ 它只能交回一句
       "我原样交回"（而那会**真的**变成那一份的正文）。
    ⚠️ **一份一份地摆**（名字 ＋ 逐字正文）：那是这一条消息里**唯一**能把
       "哪一段是哪一份"说清的办法（没有工具、没有文件名可点）。
    ⚠️ **次序由调用方给**（照 `consolidate.HER_FILES` —— 与写下去那一条同序）：
       两处一个次序，日志与判据都读得出来。
    ⚠️ **正文一个字节都不动**（不 strip、不截断）：它是那一份**现状**的正文 ——
       在这里动它，等于让模型照着一份**改过的**东西去改。
    ⚠️ **`instruct` 可换**（缺省是那一段正身）：判据可以把一段短的递进来 ——
        于是"怎么排这几段"与"那几段话本身"各判各的，互不牵制。
    """
    lines = [instruct, "", STATE_HEADING, ""]
    for name, text in blocks:
        lines.append(f"—— {name} ——")
        lines.append(text if text else STATE_EMPTY)
        lines.append("")
    return "\n".join(lines)
